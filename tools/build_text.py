# ---------------------------------------------------------------- structural markup
lines = T.split('\n')
out = []
for l in lines:
    if l in ('✦', '•'):
        out.append('*'); continue
    if l.startswith('#'):
        out.append(l); continue
    m = re.match(r'^السِّفْرُ ([^:]+): (.+)$', l)
    if m:
        out.append(f'#PART|السِّفْرُ {m.group(1)}|{m.group(2)}'); continue
    m = re.match(r'^([٠-٩]+) \| (.+)$', l)
    if m:
        out.append(f'#CH|{m.group(1)}|{m.group(2)}'); continue
    if re.match(r'^— تمّ السفر .+ —$', l):
        out.append('#ENDPART|' + l); continue
    if l == 'تمّت':
        out.append('#FIN|تمّت'); continue
    if l == 'القاهرة — الأقصر':
        out.append('#SIGN|القاهرة — الأقصر'); continue
    out.append(l)
# collapse repeated/edge separators
clean = []
for l in out:
    if l == '*' and clean and (clean[-1] == '*' or clean[-1].startswith('#')):
        continue
    if l.startswith('#') and clean and clean[-1] == '*':
        clean.pop()
    clean.append(l)
open(D + 'novel.txt', 'w', encoding='utf-8').write('\n'.join(clean) + '\n')
print('blocks:', len(clean), 'words:', len(' '.join(clean).split()))
